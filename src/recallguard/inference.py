"""Shared validation, artifact loading and prediction for CLI, UI and API."""

import logging
import os
from importlib.metadata import version
from pathlib import Path
from tempfile import NamedTemporaryFile
from typing import Annotated, Literal

import joblib
import numpy as np
import pandas as pd
from pydantic import BaseModel, ConfigDict, StringConstraints, model_validator

from recallguard.data import FEATURES, feature_frame, normalize
from recallguard.training import probability, raw_scores

LOGGER = logging.getLogger(__name__)
LONG = Annotated[str, StringConstraints(strip_whitespace=True, max_length=16000)]
SHORT = Annotated[str, StringConstraints(strip_whitespace=True, max_length=240)]
LIMITATION = (
    "Priority reflects association with historical linkage labels in a sampled dataset."
)
PACKAGES = ("scikit-learn", "numpy", "scipy", "pandas", "joblib", "xgboost")


class IncidentRequest(BaseModel):
    model_config = ConfigDict(extra="forbid", strict=True)
    product: LONG = ""
    description: LONG = ""
    category: SHORT = ""
    brand: SHORT = ""
    manufacturer: SHORT = ""
    product_type: SHORT = ""

    @model_validator(mode="after")
    def require_text(self):
        if not (normalize(self.product) or normalize(self.description)):
            raise ValueError("Provide a product or incident description")
        return self


class Contribution(BaseModel):
    feature: str
    effect: float


class Prediction(BaseModel):
    model: str
    priority_score: float
    priority: Literal["Low", "Moderate", "High"]
    contributions: list[Contribution]
    limitation: str = LIMITATION


def versions() -> dict:
    return {package: version(package) for package in PACKAGES}


def save_model(bundle: dict, path: Path) -> None:
    """Atomically publish a trained model to a local, operator-managed location."""
    path.parent.mkdir(parents=True, exist_ok=True)
    bundle["metadata"].update(
        format_version=1,
        packages=versions(),
        features=list(FEATURES),
        labels={"0": "other historical observation", "1": "record-linked observation"},
    )
    with NamedTemporaryFile(dir=path.parent, delete=False) as handle:
        temporary = Path(handle.name)
    try:
        joblib.dump(bundle, temporary, compress=3)
        temporary.replace(path)
    finally:
        temporary.unlink(missing_ok=True)


def load_model(path: Path) -> dict:
    """Load only a known, trusted local bundle generated by the training command."""
    bundle = joblib.load(path)
    metadata = bundle["metadata"]
    if metadata["format_version"] != 1 or metadata["packages"] != versions():
        raise ValueError(
            "Artifact version mismatch. Regenerate it in the serving environment."
        )
    return bundle


def configured_model() -> dict | None:
    """An operator must explicitly configure the trusted artifact path."""
    model_path = os.environ.get("RECALLGUARD_MODEL")
    if model_path:
        try:
            return load_model(Path(model_path))
        except Exception:
            LOGGER.exception("Configured RecallGuard bundle could not be loaded")
    return None


def global_features(bundle: dict, size: int = 10) -> list[dict]:
    pipeline = bundle["pipeline"]
    model = pipeline.named_steps["classifier"]
    names = pipeline.named_steps["preprocess"].get_feature_names_out()
    if hasattr(model, "coef_"):
        weights = model.coef_[0]
        order = np.argsort(weights)
        indices = [*order[:size], *order[-size:][::-1]]
    elif hasattr(model, "feature_importances_"):
        weights = model.feature_importances_
        indices = np.argsort(weights)[-size:][::-1]
    else:
        return []
    return [{"feature": str(names[i]), "weight": float(weights[i])} for i in indices]


def predict(bundle: dict, request: IncidentRequest) -> Prediction:
    pipeline = bundle["pipeline"]
    features = feature_frame(pd.DataFrame([request.model_dump()]))
    score = float(probability(bundle["calibrator"], raw_scores(pipeline, features))[0])
    priority = (
        "High"
        if score >= bundle["high"]
        else "Moderate"
        if score >= bundle["low"]
        else "Low"
    )
    model = pipeline.named_steps["classifier"]
    contributions = []
    if hasattr(model, "coef_"):
        preprocess = pipeline.named_steps["preprocess"]
        values = preprocess.transform(features)
        row = values.toarray().ravel() if hasattr(values, "toarray") else values.ravel()
        effects = row * model.coef_[0]
        names = preprocess.get_feature_names_out()
        contributions = [
            Contribution(feature=str(names[i]), effect=float(effects[i]))
            for i in np.argsort(-np.abs(effects))[:10]
            if effects[i]
        ]
    elif hasattr(model, "get_booster"):
        from xgboost import DMatrix

        preprocess = pipeline.named_steps["preprocess"]
        effects = model.get_booster().predict(
            DMatrix(preprocess.transform(features)), pred_contribs=True
        )[0, :-1]
        names = preprocess.get_feature_names_out()
        contributions = [
            Contribution(feature=str(names[i]), effect=float(effects[i]))
            for i in np.argsort(-np.abs(effects))[:10]
            if effects[i]
        ]
    return Prediction(
        model=bundle["metadata"]["selected"],
        priority_score=score,
        priority=priority,
        contributions=contributions,
    )
